namespace SadGallery.Domain.Enums;

/// <summary>
/// نوع فایل بارگذاری‌شده (فاز ۴). این تفکیک یک «قرارداد امنیتی» است، نه فقط دسته‌بندی.
/// </summary>
/// <remarks>
/// قاعده پروژه (مستر پرامپت): «تصاویر محصول عمومی را از فایل‌های خصوصی احتمالی جدا نگه دار».
/// </remarks>
public enum MediaKind
{
    /// <summary>
    /// تصویر عمومی محصول. تنها این نوع است که از مسیر ایستا (<c>/media/products</c>) قابل دسترسی است.
    /// </summary>
    PublicImage = 1,

    /// <summary>
    /// فایل خصوصی (مثلاً پیوست‌های آینده). هرگز مسیر ایستا ندارد؛
    /// فقط از طریق یک کنترلر دارای مجوز و بدون هیچ حدس‌پذیری در نام، ارائه می‌شود.
    /// </summary>
    PrivateFile = 2,
}
