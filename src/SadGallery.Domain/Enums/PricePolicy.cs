namespace SadGallery.Domain.Enums;

/// <summary>
/// سیاست قیمت‌گذاری یک محصول (فاز ۴).
/// </summary>
/// <remarks>
/// چرا سه حالت؟ چون در بازار طلا همه کالاها قیمت قطعی ندارند: برخی قیمت ثابت دارند،
/// برخی بر اساس نرخ روز محاسبه می‌شوند و برخی فقط با استعلام قیمت فروخته می‌شوند.
/// نمایش عددی که «محاسبه نشده» یا «کهنه» است، بدتر از نمایش ندادن آن است.
/// </remarks>
public enum PricePolicy
{
    /// <summary>قیمت ثابت (تومان) که اپراتور وارد می‌کند.</summary>
    Fixed = 1,

    /// <summary>
    /// محاسبه‌شده از فرمول: ارزش طلا (بر پایه نرخ روز) + اجرت + سود + مالیات.
    /// مبنای محاسبه و زمان محاسبه باید ذخیره و نمایش داده شود (معیار پذیرش فاز ۴).
    /// </summary>
    Computed = 2,

    /// <summary>فقط استعلام قیمت؛ هیچ عددی روی سایت نمایش داده نمی‌شود.</summary>
    QuoteOnly = 3,
}
